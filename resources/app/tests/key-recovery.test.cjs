'use strict';
const {test}=require('node:test'),assert=require('node:assert/strict'),path=require('node:path');
const fixture=require('./helpers/transfer-fixture.cjs'),crypto=require('../privacy/crypto.cjs');
const {PrivateClient}=require('../desktop/private-client.cjs');
const password='Synthetic-audit-password-123';

test('lost PC recovery requires the teacher, a live request and a reauthenticated admin; old sessions and keys are revoked',()=>fixture(async({a,b,c,users,tokens,send,call,root,clients,advance,sql,restart})=>{
  const target=users.b.id,oldKey=crypto.publicIdentity(b.identity),oldNumber=await crypto.fingerprint(oldKey);
  await a.verify(target,oldNumber);
  await send(b,'already-saved',[users.a.id]);await a.request('/bootstrap');
  await send(a,'pending-group',[target,users.c.id]);
  const scheduled=(sender,id,to)=>sender.request('/sync',{operations:[{type:'mail.send',value:{id,title:id,body:id,to,cc:[],files:[],scheduled:new Date(Date.now()+86400000).toISOString()}}]});
  await scheduled(b,'old-scheduled',[users.c.id]);await scheduled(a,'only-lost',[target]);
  const replacement=new PrivateClient({root:path.join(root,'replacement'),server:b.server,user:users.b,request:(r,p)=>call('b',r,p),protector:{encrypt:s=>Buffer.from(s),decrypt:b=>b.toString()}});
  clients.push(replacement);await assert.rejects(replacement.request('/bootstrap'),e=>e.code==='KEY_REGISTRATION_CONFLICT');
  const issue=()=>replacement.requestKeyRecovery(true);
  const approve=(code,overrides={},actor='a')=>call(actor,'/admin/key-recovery',{id:target,code,password,confirmed:true,...overrides});
  const expired=await issue();await advance(15*60*1000);assert.equal((await approve(expired.code)).status,409);
  const first=await issue();await restart();assert.equal((await approve(first.code)).status,409);
  const request=await issue();assert.equal((await approve(request.code,{},'c')).status,403);
  assert.equal((await approve(request.code,{password:'wrong'})).status,403);
  assert.equal((await approve(request.code,{confirmed:false})).status,409);
  assert.equal((await approve(request.code,{id:users.c.id})).status,409);
  assert.equal((await approve('0000-0000-0000')).status,409);
  assert.equal(sql('SELECT fingerprint FROM privacy_keys WHERE user_id=?',[target])[0].fingerprint,oldNumber);
  const priorKeys=await a.keys(),ctx={...crypto.context('relay','stale-wire',users.a.id,[target]),sequence:1000,releaseAt:0,files:[]};
  const sealed=await crypto.encrypt({type:'fixture'},ctx,a.identity,priorKeys);
  assert.equal((await approve(request.code)).status,200);
  assert.equal((await approve(request.code)).status,409);
  assert.equal((await call('b','/relay/pull')).status,401);
  assert.equal((await call('a','/relay/send',{context:ctx,sealed})).status,409);
  assert.equal(sql('SELECT count(*) n FROM relay_targets WHERE user_id=?',[target])[0].n,0);
  assert.equal(sql('SELECT count(*) n FROM relay_packets WHERE sender=?',[target])[0].n,0);
  assert.equal(sql('SELECT approved_by FROM privacy_key_changes WHERE user_id=?',[target])[0].approved_by,users.a.id);
  await restart();
  tokens.b=(await call(null,'/login',{username:'b',password})).token;
  assert.equal((await call('b','/privacy/register',oldKey)).status,409);
  assert.equal((await call('b','/privacy/recovery',{key:oldKey,acceptLoss:true})).status,409);
  const fresh=await replacement.request('/bootstrap');assert.ok(!fresh.data.mails.some(m=>m.id==='pending-group'||m.id==='already-saved'));
  const remaining=(await c.request('/bootstrap')).data.mails;
  assert.ok(remaining.some(m=>m.id==='pending-group'));assert.ok(!remaining.some(m=>m.id==='old-scheduled'));
  assert.ok((await a.request('/bootstrap')).data.mails.some(m=>m.id==='already-saved'));
  const number=await crypto.fingerprint(crypto.publicIdentity(replacement.identity));
  assert.equal((await a.security()).people.find(p=>p.id===target).verified,false);
  await assert.rejects(a.verify(target,oldNumber),/일치/);
  await send(replacement,'new-key-mail',[users.a.id]);
  const blocked=await a.request('/bootstrap');assert.ok(blocked.incomingFailures);assert.ok(!blocked.data.mails.some(m=>m.id==='new-key-mail'));
  await a.verify(target,number);
  assert.ok((await a.request('/bootstrap')).data.mails.some(m=>m.id==='new-key-mail'));
  assert.equal((await send(a,'reply-to-new-key',[target])).delivery['reply-to-new-key'],'sent');
  assert.ok((await replacement.request('/bootstrap')).data.mails.some(m=>m.id==='reply-to-new-key'));
}));

test('a sole administrator can recover on the server PC; a failed transaction preserves delivery and the original key',()=>fixture(async({a,b,users,tokens,send,call,sql})=>{
  const account=users.a.id,original=await crypto.fingerprint(crypto.publicIdentity(a.identity));
  const next=crypto.publicIdentity(await crypto.newIdentity());
  const request=await call('a','/privacy/recovery',{key:next,acceptLoss:true});
  const approve=()=>call('a','/admin/key-recovery',{id:account,code:request.code,password,confirmed:true});
  await send(b,'waiting-for-admin',[account]);
  sql("CREATE TRIGGER fixture_reject_change BEFORE INSERT ON privacy_key_changes BEGIN SELECT RAISE(ABORT,'fixture failed write'); END",[],true);
  assert.equal((await approve()).status,500);
  assert.equal(sql('SELECT fingerprint FROM privacy_keys WHERE user_id=?',[account])[0].fingerprint,original);
  assert.ok(sql('SELECT COUNT(*) n FROM relay_targets WHERE user_id=?',[account])[0].n>0);
  assert.equal((await call('a','/privacy/keys')).status,200);
  sql('DROP TRIGGER fixture_reject_change',[],true);
  assert.equal((await approve()).status,200);
  assert.equal((await call('a','/admin/users')).status,401);
  tokens.a=(await call(null,'/login',{username:'audit',password})).token;
  assert.equal((await call('a','/privacy/register',next)).status,200);
  assert.equal((await call('a','/admin/users')).status,200);
}));
