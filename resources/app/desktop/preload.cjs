'use strict';
const {contextBridge,ipcRenderer}=require('electron');
contextBridge.exposeInMainWorld('dingdongDesktop',Object.freeze({
  mainHost: process.argv.includes('--dingdong-main-host'),
  wingWidth: Number(process.argv.find(v=>v.startsWith('--dingdong-wing-width='))?.split('=')[1])||330,
  mode: process.argv.includes('--dingdong-demo') ? 'demo' : 'installed',
  request: (route,payload)=>ipcRenderer.invoke('dingdong:request',route,payload),
  privacy: (action,value)=>ipcRenderer.invoke('dingdong:privacy',action,value),
  stageAttachment: (action,value)=>ipcRenderer.invoke('dingdong:stage-attachment',action,value),
  saveAttachment: value=>ipcRenderer.invoke('dingdong:save-attachment',value),
  connection: ()=>ipcRenderer.invoke('dingdong:connection'),
  importConnection: ()=>ipcRenderer.invoke('dingdong:import'),
  subscribe: callback=>{const listener=(_,data)=>callback(data);ipcRenderer.on('dingdong:update',listener);return ()=>ipcRenderer.removeListener('dingdong:update',listener);},
  windowAction: action=>ipcRenderer.invoke('dingdong:window',action),
  windowState: ()=>ipcRenderer.invoke('dingdong:window-state'),
  captureScreen: ()=>ipcRenderer.invoke('dingdong:capture-screen'),
  clipboardImage: ()=>ipcRenderer.invoke('dingdong:clipboard-image'),
  briefingShape: bounds=>ipcRenderer.invoke('dingdong:briefing-shape',bounds),
  openWorkspace: (page,target)=>ipcRenderer.invoke('dingdong:workspace',page,target),
  openHomeroomMemo: target=>ipcRenderer.invoke('dingdong:homeroom-memo',target),
  openMemoSchedule: note=>ipcRenderer.invoke('dingdong:memo-schedule',note),
  toggleToday: (open,position)=>ipcRenderer.invoke('dingdong:today',!!open,position),
  toggleMemo: open=>ipcRenderer.invoke('dingdong:memo',!!open),
  resizeMain: (open,position)=>ipcRenderer.invoke('dingdong:resize',!!open,position),
  openCompose: draft=>ipcRenderer.invoke('dingdong:compose',draft),
  composeDraft: ()=>ipcRenderer.invoke('dingdong:compose-draft'),
  composeSent: draft=>ipcRenderer.invoke('dingdong:compose-sent',draft),
  openChat: (room,target)=>ipcRenderer.invoke('dingdong:chat',room,target),
  openAdmin: ()=>ipcRenderer.invoke('dingdong:admin'),
  serverStatus: ()=>ipcRenderer.invoke('dingdong:server-status'),
  startServer: config=>ipcRenderer.invoke('dingdong:start-server',config),
  exportConnection: ()=>ipcRenderer.invoke('dingdong:export'),
  backupServer: ()=>ipcRenderer.invoke('dingdong:backup'),
  autoStart: enabled=>ipcRenderer.invoke('dingdong:auto-start',!!enabled),
  notify: (title,body,target)=>ipcRenderer.invoke('dingdong:notify',{title,body,target})
}));
